// validOS is the set of supported operating systems for agent binaries.
var validOS = map[string]bool{
	"linux":   true,
	"darwin":  true,
	"freebsd": true,
	"openbsd": true,
	"netbsd":  true,
	"illumos": true,
	"windows": true,
}

// validArch is the set of supported architectures for agent binaries.
var validArch = map[string]bool{
	"amd64": true,
	"arm64": true,
}

// Handler serves the bootstrap script, agent latest version info, agent
// binary downloads, and bootstrap registration with CSR signing.
type Handler struct {
	serverAddr      string
	caFile          string
	agentDir        string
	version         string
	cache           *checksumCache
	ca              *ca.CA
	registry        *registry.Registry
	trustedPatterns []config.TrustedEnrollment
	certValidity    time.Duration
	dispatcher      *webhook.Dispatcher
	fleetIndex      *fleet.FleetIndex
}

// NewHandler creates a Handler for serving bootstrap and agent distribution endpoints.
func NewHandler(serverAddr, caFile, agentDir, version string) *Handler {
	return &Handler{
		serverAddr:   serverAddr,
		caFile:       caFile,
		agentDir:     agentDir,
		version:      version,
		cache:        newChecksumCache(),
		certValidity: 365 * 24 * time.Hour, // default 1 year
	}
}

// SetCA configures the certificate authority for CSR signing during bootstrap.
func (h *Handler) SetCA(c *ca.CA) { h.ca = c }

// SetRegistry configures the enrollment registry for bootstrap registration.
func (h *Handler) SetRegistry(r *registry.Registry) { h.registry = r }

// SetTrustedPatterns configures trusted enrollment patterns for token-free registration.
func (h *Handler) SetTrustedPatterns(patterns []config.TrustedEnrollment) {
	h.trustedPatterns = patterns
}

// SetCertValidity sets the validity duration for signed client certificates.
func (h *Handler) SetCertValidity(d time.Duration) { h.certValidity = d }

// SetDispatcher configures the webhook dispatcher for enrollment events.
func (h *Handler) SetDispatcher(d *webhook.Dispatcher) { h.dispatcher = d }

// SetFleetIndex configures the in-memory fleet index for immediate thrall availability after bootstrap.
func (h *Handler) SetFleetIndex(fi *fleet.FleetIndex) { h.fleetIndex = fi }

// RegisterRoutes registers the bootstrap and agent distribution routes on the mux.
func (h *Handler) RegisterRoutes(mux *http.ServeMux) {
	mux.HandleFunc("GET /bootstrap", h.BootstrapScript)
	mux.HandleFunc("GET /api/v1/agent/latest", h.AgentLatest)
	mux.HandleFunc("GET /api/v1/agent/download/{os}/{arch}", h.AgentDownload)
	mux.HandleFunc("POST /api/v1/bootstrap/register", h.BootstrapRegister)
}

// bootstrapData is the template data for the bootstrap shell script.
type bootstrapData struct {
	ServerAddr string
	Token      string
	CACert     string
}

// bootstrapTmpl is the shell script served at GET /bootstrap.
// Token is optional — if empty, the agent uses trusted enrollment (CSR-only).
// All interpolated values are single-quoted to prevent shell injection.
var bootstrapTmpl = template.Must(template.New("bootstrap").Parse(`#!/bin/sh
set -eu

# Hobnob Agent Bootstrap Script
# Generated by the Hobnob server.

SERVER_ADDR='{{.ServerAddr}}'
TOKEN='{{.Token}}'

# Detect OS and architecture.
OS="$(uname -s | tr '[:upper:]' '[:lower:]')"
# illumos reports as "sunos" — map to "illumos".
if [ "$OS" = "sunos" ]; then
    OS="illumos"
fi
ARCH="$(uname -m)"
case "$ARCH" in
    x86_64) ARCH="amd64" ;;
    aarch64|arm64) ARCH="arm64" ;;
    *) echo "Unsupported architecture: $ARCH"; exit 1 ;;
esac

echo "Detected platform: ${OS}/${ARCH}"
echo "Server: ${SERVER_ADDR}"

# Directories.
INSTALL_DIR="/usr/local/sbin"
DATA_DIR="/etc/hobnob-thrall"

# Stop existing service and clean up stale state for a fresh bootstrap.
if command -v systemctl > /dev/null 2>&1 && systemctl is-active --quiet hobnob-thrall 2>/dev/null; then
    echo "Stopping existing hobnob-thrall service..."
    systemctl stop hobnob-thrall
elif command -v launchctl > /dev/null 2>&1 && launchctl list com.hobnob.thrall > /dev/null 2>&1; then
    echo "Stopping existing hobnob-thrall service..."
    launchctl unload /Library/LaunchDaemons/com.hobnob.thrall.plist 2>/dev/null || true
elif command -v rcctl > /dev/null 2>&1 && rcctl get hobnob_thrall status > /dev/null 2>&1; then
    echo "Stopping existing hobnob-thrall service..."
    rcctl stop hobnob_thrall 2>/dev/null || true
elif command -v svcadm > /dev/null 2>&1 && svcs -H hobnob-thrall > /dev/null 2>&1; then
    echo "Stopping existing hobnob-thrall service..."
    svcadm disable -s svc:/system/hobnob-thrall:default 2>/dev/null || true
elif [ -x /usr/local/etc/rc.d/hobnob_thrall ]; then
    echo "Stopping existing hobnob-thrall service..."
    /usr/local/etc/rc.d/hobnob_thrall stop 2>/dev/null || true
fi

# Remove old data directory for a clean enrollment.
if [ -d "$DATA_DIR" ]; then
    echo "Removing previous enrollment data..."
    rm -rf "$DATA_DIR"
fi
mkdir -p "$DATA_DIR"

# Remove stale binary at old install path (moved from /usr/local/bin to /usr/local/sbin).
rm -f /usr/local/bin/hobnob
# Clear shell command cache so the new path is found immediately.
hash -r 2>/dev/null || true

# Download agent binary (always replaces existing).
echo "Downloading agent binary..."
curl -sSfk "${SERVER_ADDR}/api/v1/agent/download/${OS}/${ARCH}" -o "${INSTALL_DIR}/hobnob"
chmod +x "${INSTALL_DIR}/hobnob"

# Bootstrap the agent (generates keys, CSR, registers with server, receives certs).
# Always pass --force: this script cleans local state above, so re-enrollment is expected.
echo "Bootstrapping agent..."
BOOTSTRAP_ARGS="--server ${SERVER_ADDR} --force"
if [ -n "$TOKEN" ]; then
    BOOTSTRAP_ARGS="${BOOTSTRAP_ARGS} --token ${TOKEN}"
fi
"${INSTALL_DIR}/hobnob" --data-dir "${DATA_DIR}" bootstrap ${BOOTSTRAP_ARGS}

# Extract gRPC server address (strip protocol and port, add :1530).
# Install service based on detected init system.
# The agent reads server address from ${DATA_DIR}/config written during bootstrap.
# No --server flag needed — the config file is the single source of truth.
if command -v systemctl > /dev/null 2>&1; then
    # Linux (systemd)
    cat > /etc/systemd/system/hobnob-thrall.service << SYSTEMD
[Unit]
Description=Hobnob State Enforcement Agent
After=network.target

[Service]
Type=simple
ExecStart=/usr/local/sbin/hobnob
Restart=always
RestartSec=10

[Install]
WantedBy=multi-user.target
SYSTEMD
    systemctl daemon-reload
    systemctl enable hobnob-thrall
    systemctl start hobnob-thrall
    echo "Hobnob agent service installed and started (systemd)."
elif command -v launchctl > /dev/null 2>&1; then
    # macOS (launchd) — uses /usr/local/etc/hobnob-thrall as data dir.
    DATA_DIR="/usr/local/etc/hobnob-thrall"
    mkdir -p "$DATA_DIR"
    cat > /Library/LaunchDaemons/com.hobnob.thrall.plist << PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key><string>com.hobnob.thrall</string>
    <key>ProgramArguments</key>
    <array>
        <string>/usr/local/sbin/hobnob</string>
        <string>--data-dir</string><string>/usr/local/etc/hobnob-thrall</string>
    </array>
    <key>RunAtLoad</key><true/>
    <key>KeepAlive</key><true/>
</dict>
</plist>
PLIST
    launchctl load -w /Library/LaunchDaemons/com.hobnob.thrall.plist
    echo "Hobnob agent service installed and started (launchd)."
elif command -v rcctl > /dev/null 2>&1; then
    # OpenBSD (rcctl)
    cat > /etc/rc.d/hobnob_thrall << 'RCSCRIPT'
#!/bin/ksh
daemon="/usr/local/sbin/hobnob"
daemon_flags=""
. /etc/rc.d/rc.subr
rc_cmd $1
RCSCRIPT
    chmod 755 /etc/rc.d/hobnob_thrall
    rcctl enable hobnob_thrall
    rcctl start hobnob_thrall
    echo "Hobnob agent service installed and started (rcctl)."
elif command -v svccfg > /dev/null 2>&1 && command -v svcadm > /dev/null 2>&1; then
    # illumos (SMF)
    cat > /var/svc/manifest/system/hobnob-thrall.xml << SMFMANIFEST
<?xml version="1.0"?>
<!DOCTYPE service_bundle SYSTEM "/usr/share/lib/xml/dtd/service_bundle.dtd.1">
<service_bundle type="manifest" name="hobnob-thrall">
  <service name="system/hobnob-thrall" type="service" version="1">
    <create_default_instance enabled="false"/>
    <single_instance/>
    <dependency name="network" grouping="require_all" restart_on="error" type="service">
      <service_fmri value="svc:/milestone/network:default"/>
    </dependency>
    <dependency name="filesystem" grouping="require_all" restart_on="error" type="service">
      <service_fmri value="svc:/system/filesystem/local"/>
    </dependency>
    <exec_method type="method" name="start"
      exec="/usr/local/sbin/hobnob &amp;"
      timeout_seconds="60">
      <method_context><method_credential user="root" group="root"/></method_context>
    </exec_method>
    <exec_method type="method" name="stop" exec=":kill" timeout_seconds="60"/>
    <template>
      <common_name><loctext xml:lang="C">Hobnob State Enforcement Agent</loctext></common_name>
    </template>
  </service>
</service_bundle>
SMFMANIFEST
    svccfg import /var/svc/manifest/system/hobnob-thrall.xml
    svcadm enable svc:/system/hobnob-thrall:default
    echo "Hobnob agent service installed and started (SMF)."
elif [ -d /etc/rc.d ] && [ -f /etc/rc.subr ]; then
    # FreeBSD / NetBSD (rc.d)
    RCDIR="/usr/local/etc/rc.d"
    if [ "$(uname -s)" = "NetBSD" ]; then
        RCDIR="/etc/rc.d"
    fi
    mkdir -p "$RCDIR"
    cat > "${RCDIR}/hobnob_thrall" << RCSCRIPT
#!/bin/sh
# PROVIDE: hobnob_thrall
# REQUIRE: NETWORKING
# KEYWORD: shutdown
. /etc/rc.subr
name="hobnob_thrall"
rcvar="\${name}_enable"
command="/usr/local/sbin/hobnob"
command_args="&"
pidfile="/var/run/\${name}.pid"
load_rc_config \$name
: \${hobnob_thrall_enable:=NO}
run_rc_command "\$1"
RCSCRIPT
    chmod 755 "${RCDIR}/hobnob_thrall"
    if command -v sysrc > /dev/null 2>&1; then
        sysrc hobnob_thrall_enable=YES
    else
        grep -q 'hobnob_thrall=YES' /etc/rc.conf 2>/dev/null || echo 'hobnob_thrall=YES' >> /etc/rc.conf
    fi
    service hobnob_thrall start 2>/dev/null || "${RCDIR}/hobnob_thrall" start
    echo "Hobnob agent service installed and started (rc.d)."
else
    echo "No supported init system found. Start the agent manually:"
    echo "  hobnob"
fi

echo "Bootstrap complete."
`))

