package audit

import (
	"crypto/sha256"
	"encoding/hex"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// frenchMarkerRe extracts the source-sha hex from a French doc's first-line
// provenance marker:
//
//	<!-- vigo-i18n source_sha:HEX -->
//
// HEX is the lowercase sha256 of the English source file's raw bytes. The ui
// docs browser strips this marker before rendering (ui.stripDocI18nMarker);
// this audit verifies it still matches the English source.
var frenchMarkerRe = regexp.MustCompile(`^<!-- vigo-i18n source_sha:([0-9a-fA-F]+) -->`)

// TestFrenchDocsNotStale walks docs/fr/**/*.md and verifies each translated
// file carries a first-line provenance marker whose sha256 matches its English
// source. An English edit without a French regen makes this loud.
//
// The French tree is generated by a separate job; each file is written
// complete-with-marker, so any file present is valid — running this mid-
// generation is safe (it only checks files that exist). If docs/fr/ doesn't
// exist yet, the test passes vacuously. It deliberately does NOT require every
// English file to have a French counterpart — the reference tree is
// intentionally untranslated.
func TestFrenchDocsNotStale(t *testing.T) {
	root := repoRoot(t)
	frRoot := filepath.Join(root, "docs", "fr")

	if info, err := os.Stat(frRoot); err != nil || !info.IsDir() {
		t.Skip("docs/fr/ not present — nothing to audit")
	}

	var checked int
	err := filepath.Walk(frRoot, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() || !strings.HasSuffix(path, ".md") {
			return nil
		}

		// Derive the English path by dropping the single "fr/" segment:
		// docs/fr/start/x.md -> docs/start/x.md.
		rel, relErr := filepath.Rel(filepath.Join(root, "docs", "fr"), path)
		if relErr != nil {
			t.Errorf("%s: cannot compute relative path: %v", path, relErr)
			return nil
		}
		enPath := filepath.Join(root, "docs", rel)

		enRaw, enErr := os.ReadFile(enPath)
		if enErr != nil {
			t.Errorf("%s: English source missing at %s (orphaned French translation): %v",
				path, enPath, enErr)
			return nil
		}
		wantSum := sha256.Sum256(enRaw)
		wantHex := hex.EncodeToString(wantSum[:])

		frRaw, frErr := os.ReadFile(path)
		if frErr != nil {
			t.Errorf("%s: cannot read French file: %v", path, frErr)
			return nil
		}
		firstLine := frRaw
		if i := strings.IndexByte(string(frRaw), '\n'); i >= 0 {
			firstLine = frRaw[:i]
		}
		m := frenchMarkerRe.FindStringSubmatch(strings.TrimRight(string(firstLine), "\r"))
		if m == nil {
			t.Errorf("%s: missing first-line marker `<!-- vigo-i18n source_sha:HEX -->` "+
				"(every French doc must carry the provenance marker)", path)
			return nil
		}
		gotHex := strings.ToLower(m[1])
		if gotHex != wantHex {
			t.Errorf("%s: STALE — marker sha %s != English source sha %s "+
				"(regenerate the French translation of %s)",
				path, gotHex, wantHex, enPath)
		}
		checked++
		return nil
	})
	if err != nil {
		t.Fatalf("walking %s: %v", frRoot, err)
	}
	t.Logf("checked %d French doc file(s) against English sources", checked)
}
