//! Per-user cryptsync config + file paths.
//!
//! Files live under `~<user>/.cryptsync/`:
//!
//! - `config.yaml` — YAML with optional `cross_subnet_peers: [hostname, ...]`
//!   and `idle_timeout_minutes: <int>`. Missing file = defaults
//!   (LAN-only, 60 m idle timeout).
//! - `identity.age` — **wrapped** age private key. Binary format:
//!   `[1 byte version][24 byte XChaCha20-Poly1305 nonce][ciphertext + 16 byte tag]`.
//!   Mode 0600.
//! - `identity.salt` — 16-byte random salt used as Argon2id input.
//!   Mode 0600.
//! - `recipients.txt` — one age public key per line, `#` comments
//!   allowed. Includes this envoy's own pubkey. Regenerated by the
//!   agent from the peer table when peers come and go.
//! - `enroll.pending` — empty sentinel file dropped by the user
//!   executor when `cryptsync: true` is set. First `vigo swarm cryptsync *`
//!   invocation detects it and runs enrollment.
//!
//! Agent-owned state lives at `/var/lib/vigo/swarm/cryptsync/<username>/`:
//!
//! - `peers.json` — known cryptsync peers for this user (hostname,
//!   pubkey, last_seen). Root-owned, 0600. Agent-exclusive; kept
//!   outside the user's home so the user's `~/.cryptsync/` is
//!   cleanly "my keys + who I trust."
//!
//! Unlike filesync, cryptsync never writes a plaintext identity to
//! disk. The wrap key is derived from the user's cryptsync password
//! via Argon2id; only the per-user session helper (week 3) holds the
//! unwrapped bytes at runtime, and only in memory.

use std::fs;
use std::path::{Path, PathBuf};

use age::x25519::Recipient;
use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};

/// `~<user>/.cryptsync/` — the per-user state dir.
pub fn dot_dir(home: &Path) -> PathBuf {
    home.join(".cryptsync")
}

/// `~<user>/cryptsync/` — the per-user ciphertext directory.
pub fn content_dir(home: &Path) -> PathBuf {
    home.join("cryptsync")
}

pub fn config_path(home: &Path) -> PathBuf {
    dot_dir(home).join("config.yaml")
}

pub fn identity_path(home: &Path) -> PathBuf {
    dot_dir(home).join("identity.age")
}

pub fn salt_path(home: &Path) -> PathBuf {
    dot_dir(home).join("identity.salt")
}

// Signing identity is daemon-owned (not user-wrapped) so DELETE
// envelopes can be signed autonomously without requiring the user to
// unlock. See `signing_key_path` / `signing_pubkey_path` below — both
// live under `agent_state_dir` alongside `peers.json`.

pub fn recipients_path(home: &Path) -> PathBuf {
    dot_dir(home).join("recipients.txt")
}

/// User-side mirror of the daemon's tombstone table. Written by the
/// daemon after every canonical save to `agent_state_dir/<user>/
/// tombstones.json`; consumed by `vigo swarm cryptsync list` / `status` running
/// as the user. Same content, different ACL surface — the canonical
/// file stays root-only, the mirror is chown'd to the user 0600.
pub fn tombstones_user_path(home: &Path) -> PathBuf {
    dot_dir(home).join("tombstones.json")
}

/// User-side mirror of the daemon's leaves table. Same rationale as
/// `tombstones_user_path` — root-owned canonical at
/// `agent_state_dir/<user>/leaves.json`, user-readable mirror in
/// `~/.cryptsync/`.
pub fn leaves_user_path(home: &Path) -> PathBuf {
    dot_dir(home).join("leaves.json")
}

pub fn enroll_pending_path(home: &Path) -> PathBuf {
    dot_dir(home).join("enroll.pending")
}

/// Sentinel file that tells the daemon reactor to process a
/// self-leave. Dropped by `vigo swarm cryptsync leave` (running as the user);
/// consumed by the daemon (running as root) — the daemon signs the
/// LEAVE envelope, fans it out to live peers, and scrubs per the
/// sentinel's flags. Removed by the daemon on successful processing.
pub fn leave_pending_path(home: &Path) -> PathBuf {
    dot_dir(home).join("leave.pending")
}

/// Sentinel file that tells the session helper to drain a pending
/// reencrypt. Dropped when a LEAVE lands and recipients.txt changes;
/// cleared after `cmd_reencrypt` runs successfully.
pub fn reencrypt_pending_path(home: &Path) -> PathBuf {
    dot_dir(home).join("reencrypt.pending")
}

/// Liveness sentinel written by the session helper (`daemon_main`)
/// at startup and removed at shutdown. Content: the helper's PID, one
/// line, `0600` user-owned. Lives under the user's home so the
/// root-context watcher can read it without having to discover a
/// per-platform runtime dir (`/run/user/<uid>/vigo/` on Linux,
/// `$TMPDIR/cryptsync-<uid>/` on macOS — opaque to root). The watcher
/// uses this to gate auto-encrypt-on-write per ADR-012: file present
/// + PID alive ⇒ session unlocked ⇒ encrypt; otherwise leave the
/// plaintext in place for the unlock sweep to pick up.
pub fn session_unlocked_path(home: &Path) -> PathBuf {
    dot_dir(home).join("session.unlocked")
}

/// Sentinel file that tells the daemon reactor to regenerate
/// `recipients.txt` from the daemon-side `peers.json` immediately.
/// Dropped by `vigo swarm cryptsync enroll` after seeding the user-side files
/// — the daemon picks it up on the next reactor tick (≤30 s) and
/// folds existing live peers into the freshly-seeded recipients.
/// Without this, post-reenroll recipients.txt would stay at "self
/// only" until a peer rotated its pubkey or aged out, since the
/// announce path skips regeneration on heartbeat-only upserts.
/// Cleared by the daemon after the regen runs.
pub fn regen_pending_path(home: &Path) -> PathBuf {
    dot_dir(home).join("regen.pending")
}

/// `/var/lib/vigo/swarm/cryptsync/<username>/` — root-owned state dir for
/// one user's peer table and reactor bookkeeping. Created lazily.
pub fn agent_state_dir(username: &str) -> PathBuf {
    PathBuf::from("/var/lib/vigo/swarm/cryptsync").join(username)
}

pub fn peers_path(username: &str) -> PathBuf {
    agent_state_dir(username).join("peers.json")
}

/// Persisted LEAVE records — signed envelopes accepted from peers
/// plus self-leaves. Root-owned 0600. Participates in digest gossip
/// alongside tombstones so offline-during-leave peers catch up.
pub fn leaves_path(username: &str) -> PathBuf {
    agent_state_dir(username).join("leaves.json")
}

/// Raw Ed25519 private signing key (32 bytes). Root-owned, 0600.
/// Generated lazily by the cryptsync daemon on first announce after
/// a user is enrolled.
pub fn signing_key_path(username: &str) -> PathBuf {
    agent_state_dir(username).join("signing.key")
}

/// Ed25519 signing pubkey in `ed25519:<hex>` form — plaintext, one
/// line + newline. Root-owned, 0644. Advertised on every
/// announcement so peers can verify DELETE envelopes from this host.
pub fn signing_pubkey_path(username: &str) -> PathBuf {
    agent_state_dir(username).join("signing.pub")
}

/// Per-user cryptsync settings. Default (missing file) = LAN-only,
/// 60 m idle timeout.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UserConfig {
    /// Hostnames of cross-subnet receivers unreachable via multicast.
    /// The sender POSTs recipient announcements to each peer's
    /// `https://<host>:1531/swarm/cryptsync/announce`. Empty by default.
    #[serde(default)]
    pub cross_subnet_peers: Vec<String>,

    /// Minutes of inactivity before the session helper auto-locks.
    /// Resets on every `decrypt` call. Default 60.
    #[serde(default = "default_idle_minutes")]
    pub idle_timeout_minutes: u32,
}

fn default_idle_minutes() -> u32 {
    60
}

impl Default for UserConfig {
    fn default() -> Self {
        Self {
            cross_subnet_peers: Vec::new(),
            idle_timeout_minutes: default_idle_minutes(),
        }
    }
}

/// Load the user's config file. Missing or malformed = defaults +
/// a warning. Never returns an error; absence of config is the
/// common case.
pub fn load_config(home: &Path) -> UserConfig {
    let path = config_path(home);
    match fs::read_to_string(&path) {
        Ok(s) => serde_yaml::from_str(&s).unwrap_or_else(|e| {
            tracing::warn!(
                path = %path.display(),
                error = %e,
                "cryptsync: malformed config.yaml, falling back to defaults"
            );
            UserConfig::default()
        }),
        Err(_) => UserConfig::default(),
    }
}

/// Parse `recipients.txt` into a list of age recipients. Blank lines
/// and `#`-prefixed comment lines are skipped. Returns an error if the
/// file is missing, unreadable, or yields no valid recipients — the
/// caller must fail closed on error.
pub fn load_recipients(home: &Path) -> Result<Vec<Recipient>> {
    let path = recipients_path(home);
    let text = fs::read_to_string(&path)
        .with_context(|| format!("reading {}", path.display()))?;
    let mut out = Vec::new();
    for (lineno, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let r: Recipient = line.parse().map_err(|e: &str| {
            anyhow::anyhow!(
                "{}:{}: invalid age recipient: {}",
                path.display(),
                lineno + 1,
                e
            )
        })?;
        out.push(r);
    }
    if out.is_empty() {
        bail!("{} contains no recipients", path.display());
    }
    Ok(out)
}

/// True if this envoy has completed enrollment (has a wrapped
/// identity + salt on disk).
pub fn is_enrolled(home: &Path) -> bool {
    identity_path(home).exists() && salt_path(home).exists()
}

/// True if the user executor has marked this envoy for enrollment
/// but the user has not yet completed the interactive flow.
pub fn has_pending_enroll(home: &Path) -> bool {
    enroll_pending_path(home).exists()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn load_config_missing_returns_defaults() {
        let dir = tempfile::tempdir().unwrap();
        let cfg = load_config(dir.path());
        assert!(cfg.cross_subnet_peers.is_empty());
        assert_eq!(cfg.idle_timeout_minutes, 60);
    }

    #[test]
    fn load_config_parses_yaml() {
        let dir = tempfile::tempdir().unwrap();
        fs::create_dir_all(dot_dir(dir.path())).unwrap();
        let yaml = "cross_subnet_peers:\n  - host-a\n  - host-b\nidle_timeout_minutes: 30\n";
        fs::write(config_path(dir.path()), yaml).unwrap();
        let cfg = load_config(dir.path());
        assert_eq!(cfg.cross_subnet_peers, vec!["host-a".to_string(), "host-b".to_string()]);
        assert_eq!(cfg.idle_timeout_minutes, 30);
    }

    #[test]
    fn load_recipients_errors_on_missing_file() {
        let dir = tempfile::tempdir().unwrap();
        assert!(load_recipients(dir.path()).is_err());
    }

    #[test]
    fn load_recipients_skips_blank_and_comments() {
        use age::x25519::Identity;
        use std::io::Write;
        let dir = tempfile::tempdir().unwrap();
        fs::create_dir_all(dot_dir(dir.path())).unwrap();
        let id = Identity::generate();
        let pub_line = id.to_public().to_string();
        let mut f = fs::File::create(recipients_path(dir.path())).unwrap();
        writeln!(f, "# leading comment").unwrap();
        writeln!(f).unwrap();
        writeln!(f, "{}", pub_line).unwrap();
        drop(f);
        let recips = load_recipients(dir.path()).unwrap();
        assert_eq!(recips.len(), 1);
    }

    #[test]
    fn is_enrolled_false_on_empty_home() {
        let dir = tempfile::tempdir().unwrap();
        assert!(!is_enrolled(dir.path()));
    }
}
