package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"

	"github.com/spf13/cobra"
)

const (
	privateKeyFile = "hobnob_private.key"
	publicKeyFile  = "hobnob_public.key"
)

const defaultRepoPath = "/home/dan/repos/hobnob"

var keysCmd = &cobra.Command{
	Use:   "keys",
	Short: "Manage Ed25519 signing keys",
}

var keysGenerateCmd = &cobra.Command{
	Use:   "generate",
	Short: "Generate a new Ed25519 keypair for license signing",
	RunE:  runKeysGenerate,
}

var keysShowPublicCmd = &cobra.Command{
	Use:   "show-public",
	Short: "Print the public key in hex format",
	RunE:  runKeysShowPublic,
}

var keysInjectCmd = &cobra.Command{
	Use:   "inject",
	Short: "Write the public key into the hobnob source code",
	RunE:  runKeysInject,
}

var keysRotateCmd = &cobra.Command{
	Use:   "rotate",
	Short: "Rotate the keypair (invalidates all existing licenses)",
	RunE:  runKeysRotate,
}

var injectRepoPath string

func init() {
	keysInjectCmd.Flags().StringVar(&injectRepoPath, "repo", "", "Path to hobnob repo (default: /home/dan/repos/hobnob, then auto-detect)")

	keysCmd.AddCommand(keysGenerateCmd)
	keysCmd.AddCommand(keysShowPublicCmd)
	keysCmd.AddCommand(keysInjectCmd)
	keysCmd.AddCommand(keysRotateCmd)
}

func runKeysGenerate(cmd *cobra.Command, args []string) error {
	privPath := filepath.Join(keyDir, privateKeyFile)
	pubPath := filepath.Join(keyDir, publicKeyFile)

	// Refuse to overwrite existing keys.
	if _, err := os.Stat(privPath); err == nil {
		return fmt.Errorf("private key already exists at %s — use 'keys rotate' to replace", privPath)
	}
	if _, err := os.Stat(pubPath); err == nil {
		return fmt.Errorf("public key already exists at %s — use 'keys rotate' to replace", pubPath)
	}

	return generateAndSaveKeys(keyDir)
}

func runKeysShowPublic(cmd *cobra.Command, args []string) error {
	pubPath := filepath.Join(keyDir, publicKeyFile)
	data, err := os.ReadFile(pubPath)
	if err != nil {
		return fmt.Errorf("reading public key: %w\nRun 'keys generate' first.", err)
	}
	fmt.Print(string(data))
	return nil
}

func runKeysInject(cmd *cobra.Command, args []string) error {
	pubPath := filepath.Join(keyDir, publicKeyFile)
	pubHex, err := os.ReadFile(pubPath)
	if err != nil {
		return fmt.Errorf("reading public key: %w\nRun 'keys generate' first.", err)
	}

	repoPath := resolveRepoPath()
	targetFile := filepath.Join(repoPath, "server", "license", "pubkey.go")

	content := fmt.Sprintf(`package license

// PublicKeyHex is the Ed25519 public key used to verify license signatures.
// Generated by: hobnob-license-manager keys inject
// DO NOT EDIT manually — use hobnob-license-manager to update this value.
var PublicKeyHex = %q

// setPublicKeyForTest overrides the public key for testing.
func setPublicKeyForTest(key string) {
	PublicKeyHex = key
}
`, string(pubHex))

	if err := os.WriteFile(targetFile, []byte(content), 0644); err != nil {
		return fmt.Errorf("writing %s: %w", targetFile, err)
	}

	fmt.Printf("Public key injected into %s\n", targetFile)
	return nil
}

func runKeysRotate(cmd *cobra.Command, args []string) error {
	privPath := filepath.Join(keyDir, privateKeyFile)
	pubPath := filepath.Join(keyDir, publicKeyFile)

	// Remove immutable flag if set.
	removeImmutable(privPath)
	removeImmutable(pubPath)

	// Remove old keys.
	os.Remove(privPath)
	os.Remove(pubPath)

	fmt.Println("WARNING: All existing licenses are now invalid and must be re-issued.")
	fmt.Println("After generating new keys, run 'keys inject' to update the hobnob source, then rebuild.")
	fmt.Println()

	return generateAndSaveKeys(keyDir)
}

func generateAndSaveKeys(dir string) error {
	if err := os.MkdirAll(dir, 0700); err != nil {
		return fmt.Errorf("creating key directory %s: %w", dir, err)
	}

	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return fmt.Errorf("generating Ed25519 keypair: %w", err)
	}

	privHex := hex.EncodeToString(priv.Seed())
	pubHex := hex.EncodeToString(pub)

	privPath := filepath.Join(dir, privateKeyFile)
	pubPath := filepath.Join(dir, publicKeyFile)

	if err := os.WriteFile(privPath, []byte(privHex), 0400); err != nil {
		return fmt.Errorf("writing private key: %w", err)
	}
	if err := os.WriteFile(pubPath, []byte(pubHex), 0444); err != nil {
		return fmt.Errorf("writing public key: %w", err)
	}

	// Try to make files immutable.
	setImmutable(privPath)
	setImmutable(pubPath)

	fmt.Printf("Keypair generated:\n")
	fmt.Printf("  Private key: %s (KEEP SECRET)\n", privPath)
	fmt.Printf("  Public key:  %s\n", pubPath)
	fmt.Printf("\nNext step: run 'hobnob-license-manager keys inject' to embed the public key in hobnob source.\n")
	return nil
}

func setImmutable(path string) {
	cmd := exec.Command("sudo", "chattr", "+i", path)
	if err := cmd.Run(); err != nil {
		fmt.Printf("  Note: could not set immutable flag on %s (requires root)\n", path)
		fmt.Printf("  Run manually: sudo chattr +i %s\n", path)
	}
}

func removeImmutable(path string) {
	cmd := exec.Command("sudo", "chattr", "-i", path)
	_ = cmd.Run() // best-effort
}

func resolveRepoPath() string {
	// 1. Explicit flag.
	if injectRepoPath != "" {
		return injectRepoPath
	}

	// 2. Default path.
	if isHobnobRepo(defaultRepoPath) {
		return defaultRepoPath
	}

	// 3. Auto-detect: walk up from cwd.
	dir, err := os.Getwd()
	if err != nil {
		return defaultRepoPath
	}
	for {
		if isHobnobRepo(dir) {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}

	return defaultRepoPath
}

func isHobnobRepo(dir string) bool {
	data, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil {
		return false
	}
	return len(data) > 0 && contains(string(data), "github.com/hobnob/hobnob")
}

func contains(s, substr string) bool {
	return len(s) >= len(substr) && searchString(s, substr)
}

func searchString(s, substr string) bool {
	for i := 0; i <= len(s)-len(substr); i++ {
		if s[i:i+len(substr)] == substr {
			return true
		}
	}
	return false
}
