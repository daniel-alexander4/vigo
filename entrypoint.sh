#!/bin/sh
set -e

# Hobnob server entrypoint — seeds config on first run, then starts hobd.
# All persistent state lives under /srv/hobnob (bind-mounted from host).

DATA_DIR="/srv/hobnob"
HNB_PROPOSED="${DATA_DIR}/hnb/proposed"
HNB_LIVE="${DATA_DIR}/hnb/.live"
EXAMPLES_DIR="${DATA_DIR}/examples"
ENV_FILE="${DATA_DIR}/.env"
SERVER_YAML="${DATA_DIR}/server.yaml"

# Seed configs are baked into the image at /seed.
SEED_DIR="/seed"

# ---------------------------------------------------------------------------
# Create directory structure
# ---------------------------------------------------------------------------

SECRETS_DIR="${DATA_DIR}/secrets"

mkdir -p "${HNB_PROPOSED}/modules" "${HNB_PROPOSED}/roles" "${HNB_PROPOSED}/thralls" "${HNB_PROPOSED}/templates" "${HNB_PROPOSED}/vars"
mkdir -p -m 750 "${HNB_LIVE}"
mkdir -p "${DATA_DIR}/db"
mkdir -p -m 700 "${DATA_DIR}/license" "$SECRETS_DIR" "${DATA_DIR}/tls"

# ---------------------------------------------------------------------------
# Lock down license file permissions if present
# ---------------------------------------------------------------------------

for f in "${DATA_DIR}"/license/*.lic; do
    [ -f "$f" ] && chmod 600 "$f"
done

# ---------------------------------------------------------------------------
# Seed secrets for non-default configurations
# ---------------------------------------------------------------------------
# TLS certs and the default SQLite DSN are auto-generated by hobd on first
# start (via LocalProvider.EnsureTLSCerts and builtin defaults). Only Postgres
# DSN needs explicit seeding here because it depends on env vars.

if [ "${HOBNOB_DB_DRIVER}" = "postgres" ]; then
    PG_HOST="${HOBNOB_PG_HOST:-hobnob-postgres}"
    PG_PORT="${HOBNOB_PG_PORT:-5432}"
    PG_USER="${HOBNOB_PG_USER:-hobnob}"
    PG_PASS="${HOBNOB_PG_PASS:-hobnob}"
    PG_DB="${HOBNOB_PG_DB:-hobnob}"
    hobnobcli secrets set hobnob/db/dsn "postgres://${PG_USER}:${PG_PASS}@${PG_HOST}:${PG_PORT}/${PG_DB}?sslmode=disable" \
        --secrets-dir "$SECRETS_DIR" 2>/dev/null || true
fi

# ---------------------------------------------------------------------------
# Write default .env if missing (non-secret server environment only)
# ---------------------------------------------------------------------------

if [ ! -f "$ENV_FILE" ]; then
    cat > "$ENV_FILE" <<'ENVEOF'
# =============================================================================
# Hobnob Environment Configuration
# =============================================================================
# This file contains non-secret server environment variables only.
# Secrets are stored in /srv/hobnob/secrets/ (local secrets backend).
# =============================================================================

# Webhook secret for HMAC-SHA256 payload signing — store in secrets dir instead:
# echo 'my-webhook-secret' > /srv/hobnob/secrets/hobnob/webhook/secret
# HOBNOB_WEBHOOK_SECRET=change-me-to-a-random-string

# =============================================================================
# AI ASSISTANT — uncomment HOBNOB_AI_PROVIDER to enable.
# =============================================================================
# Provider options: ollama, claude, openai, openai-compat
# HOBNOB_AI_PROVIDER=ollama
# HOBNOB_AI_MODEL=qwen2.5:7b
# HOBNOB_AI_BASE_URL=http://hobnob-ollama:11434
# AI API keys must use the secret: prefix in server.yaml — never env vars.
# HOBNOB_AI_MAX_TOKENS=4096

# =============================================================================
# DATABASE DRIVER — "sqlite" (default) or "postgres"
# =============================================================================
# To use Postgres, set HOBNOB_DB_DRIVER=postgres and add "postgres" to COMPOSE_PROFILES.
# HOBNOB_DB_DRIVER=postgres
# HOBNOB_PG_HOST=hobnob-postgres
# HOBNOB_PG_PORT=5432
# HOBNOB_PG_USER=hobnob
# HOBNOB_PG_PASS=hobnob
# HOBNOB_PG_DB=hobnob

# =============================================================================
# OPTIONAL SERVICES — uncomment to enable
# =============================================================================
# These start additional Docker containers alongside hobnob.
# Set to comma-separated list: ollama, postgres, or both.
#
# HOBNOB_SERVICES=ollama              # local AI (free, CPU-only)
# HOBNOB_SERVICES=postgres            # Postgres instead of SQLite
# HOBNOB_SERVICES=ollama,postgres     # both

# Maps HOBNOB_SERVICES to Docker Compose (do not edit this line).
COMPOSE_PROFILES=${HOBNOB_SERVICES:-}
ENVEOF
    echo "Default .env created."
fi

# ---------------------------------------------------------------------------
# Copy server.yaml if missing
# ---------------------------------------------------------------------------

if [ ! -f "$SERVER_YAML" ]; then
    cp "${SEED_DIR}/server.yaml" "$SERVER_YAML"
    echo "Default server.yaml created."
fi

# ---------------------------------------------------------------------------
# Copy docker-compose.yml if missing
# ---------------------------------------------------------------------------

if [ ! -f "${DATA_DIR}/docker-compose.yml" ]; then
    cp "${SEED_DIR}/docker-compose.yml" "${DATA_DIR}/docker-compose.yml"
    echo "Default docker-compose.yml created."
fi

# ---------------------------------------------------------------------------
# Seed example configs into examples/ (skip files that already exist)
# ---------------------------------------------------------------------------

# Find all .hnb.example files under /seed/thrall-configs/ and copy them
# to /srv/hobnob/examples/ preserving directory structure.
find "${SEED_DIR}/thrall-configs" -name '*.hnb.example' -type f | while IFS= read -r src; do
    rel="${src#${SEED_DIR}/thrall-configs/}"
    dest="${EXAMPLES_DIR}/${rel}"
    if [ ! -f "$dest" ]; then
        mkdir -p "$(dirname "$dest")"
        cp "$src" "$dest"
    fi
done

# ---------------------------------------------------------------------------
# Seed documentation into bind-mounted volume
# ---------------------------------------------------------------------------

if [ -d "${SEED_DIR}/docs" ]; then
    mkdir -p "${DATA_DIR}/docs"
    cp -r "${SEED_DIR}/docs/." "${DATA_DIR}/docs/"
fi

# ---------------------------------------------------------------------------
# Install CLI tools to host (bind-mounted /usr/local/bin via /host-bin)
# ---------------------------------------------------------------------------

if [ -d /host-bin ]; then
    cp /usr/local/bin/hobnobcli /host-bin/hobnobcli
    ln -sf hobnobcli /host-bin/hnbvi
    echo "Installed hobnobcli and hnbvi to host."
fi

echo "Config seeding complete."

# ---------------------------------------------------------------------------
# Export env vars and start hobd
# ---------------------------------------------------------------------------

# Source .env so hobd sees the variables.
set -a
. "$ENV_FILE"
set +a

# ---------------------------------------------------------------------------
# Generate ai: block in server.yaml from env vars
# ---------------------------------------------------------------------------

# Inject database.driver into server.yaml if set via env var.
if [ "${HOBNOB_DB_DRIVER}" = "postgres" ]; then
    # Add driver: postgres under database: section if not already present.
    if ! grep -q 'driver:' "$SERVER_YAML"; then
        sed -i '/^database:/a\  driver: postgres' "$SERVER_YAML"
        echo "Database driver set to postgres."
    fi
fi

# Strip any existing ai: block (from previous runs).
sed -i '/^ai:/,/^[^ ]/{ /^ai:/d; /^  /d; }' "$SERVER_YAML"

if [ -n "$HOBNOB_AI_PROVIDER" ]; then
    AI_MODEL="${HOBNOB_AI_MODEL:-qwen2.5:7b}"
    AI_MAX_TOKENS="${HOBNOB_AI_MAX_TOKENS:-4096}"

    cat >> "$SERVER_YAML" <<AIEOF

ai:
  enabled: true
  provider: ${HOBNOB_AI_PROVIDER}
  model: "${AI_MODEL}"
  max_tokens: ${AI_MAX_TOKENS}
AIEOF

    [ -n "$HOBNOB_AI_BASE_URL" ] && echo "  base_url: \"${HOBNOB_AI_BASE_URL}\"" >> "$SERVER_YAML"
    # API key: use secret: prefix in server.yaml, NOT an env var.
    # Example: api_key: "secret:hobnob/ai/api_key"

    echo "AI configured: provider=${HOBNOB_AI_PROVIDER} model=${AI_MODEL}"
fi

# Seed-only mode: populate /srv/hobnob and exit without starting the server.
# Usage: docker run --rm -v /srv/hobnob:/srv/hobnob hobnob --seed-only
if [ "${1:-}" = "--seed-only" ]; then
    echo "Seeding complete. Run 'cd /srv/hobnob && docker compose up -d' to start."
    exit 0
fi

# Run from /srv/hobnob so relative paths in .env and server.yaml resolve correctly.
cd "$DATA_DIR"

export HOBNOB_CONFIG_FILE="server.yaml"
export HOBNOB_MIGRATIONS_DIR="/migrations"
export HOBNOB_AGENT_DIR="/dist/agent"

exec hobd "$@"
