#!/usr/bin/env bash
# gen-executor-schemas.sh — generates server/validate/schemas_gen.go from
# executor source code. Extracts params.get("...") calls from each Rust
# executor file and produces a Go map[string][]string keyed by type name.
#
# Run: scripts/gen-executor-schemas.sh > server/validate/schemas_gen.go

set -euo pipefail

AGENT_DIR="$(cd "$(dirname "$0")/../agent/src" && pwd)"
RUNNER="$AGENT_DIR/runner/mod.rs"
EXEC_DIR="$AGENT_DIR/executors"

# Step 1: Build type→module mapping from executors.insert() lines in runner.
# Format: type_name<TAB>module_name
declare -A TYPE_FILES

while IFS= read -r line; do
    type_name=$(echo "$line" | grep -oP 'executors\.insert\("\K[^"]+' || true)
    module_name=$(echo "$line" | grep -oP 'Box::new\(\K[a-z_]+(?=::)' || true)
    [[ -z "$type_name" || -z "$module_name" || "$type_name" == "mock" ]] && continue

    src_file=""
    if [[ -f "$EXEC_DIR/${module_name}.rs" ]]; then
        src_file="$EXEC_DIR/${module_name}.rs"
    fi
    [[ -z "$src_file" ]] && continue

    existing="${TYPE_FILES[$type_name]:-}"
    if [[ -z "$existing" ]]; then
        TYPE_FILES[$type_name]="$src_file"
    elif [[ "$existing" != *"$src_file"* ]]; then
        TYPE_FILES[$type_name]="$existing $src_file"
    fi
done < <(grep 'executors\.insert(' "$RUNNER" | grep 'Box::new(')

# Step 2: Generate Go source file.
cat <<'GOHEADER'
// Code generated by scripts/gen-executor-schemas.sh. DO NOT EDIT.
//
// Extracted from agent/src/executors/*.rs params.get("...") calls.
// Regenerate: scripts/gen-executor-schemas.sh > server/validate/schemas_gen.go

package validate

// generatedSchemas maps resource type names to attribute names extracted
// from executor source code. Merged into TypeSchemas at init time.
var generatedSchemas = map[string][]string{
GOHEADER

for type_name in $(echo "${!TYPE_FILES[@]}" | tr ' ' '\n' | sort); do
    files="${TYPE_FILES[$type_name]}"
    # Extract params.get("...") — handles both single-line and multi-line patterns.
    # Join lines first to catch .get(\n"param") patterns, then extract.
    params=$(cat $files 2>/dev/null | tr '\n' ' ' | grep -oP '\.get\(\s*"\K[^"]+' | grep -v '^_' | sort -u || true)
    if [[ -z "$params" ]]; then
        echo "	\"$type_name\": {},"
    else
        param_list=$(echo "$params" | sed 's/.*/"&"/' | paste -sd, -)
        echo "	\"$type_name\": {$param_list},"
    fi
done

# Remove duplicate "package" entry — the executor loop already emits one
# from package_windows.rs. The runner also reads "version" for package
# resources, so append it here if not already present.
# (The deduplication happens in validate.go's init when merging.)

echo "}"
