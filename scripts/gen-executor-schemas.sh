#!/usr/bin/env bash
# gen-executor-schemas.sh — generates server/validate/schemas_gen.go from
# executor source code. Extracts params.get("...") calls from each Rust
# executor file and produces a Go map[string][]string keyed by type name.
#
# Run: scripts/gen-executor-schemas.sh > server/validate/schemas_gen.go

set -euo pipefail

AGENT_DIR="$(cd "$(dirname "$0")/../agent/src" && pwd)"
RUNNER="$AGENT_DIR/runner/mod.rs"
EXEC_DIR="$AGENT_DIR/executors"

# Step 1: Build type→module mapping from executors.insert() lines in runner.
# Format: type_name<TAB>module_name
declare -A TYPE_FILES

while IFS= read -r line; do
    type_name=$(echo "$line" | grep -oP 'executors\.insert\("\K[^"]+' || true)
    module_name=$(echo "$line" | grep -oP 'Box::new\(\K[a-z_]+(?=::)' || true)
    [[ -z "$type_name" || -z "$module_name" || "$type_name" == "mock" ]] && continue

    src_file=""
    if [[ -f "$EXEC_DIR/${module_name}.rs" ]]; then
        src_file="$EXEC_DIR/${module_name}.rs"
    fi
    [[ -z "$src_file" ]] && continue

    existing="${TYPE_FILES[$type_name]:-}"
    if [[ -z "$existing" ]]; then
        TYPE_FILES[$type_name]="$src_file"
    elif [[ "$existing" != *"$src_file"* ]]; then
        TYPE_FILES[$type_name]="$existing $src_file"
    fi
done < <(grep 'executors\.insert(' "$RUNNER" | grep 'Box::new(')

# Step 2: Generate Go source file.
cat <<'GOHEADER'
// Code generated by scripts/gen-executor-schemas.sh. DO NOT EDIT.
//
// Extracted from agent/src/runner/mod.rs (executors.insert(...) registrations)
// and agent/src/executors/*.rs (params.get("...") calls). Two maps are emitted:
//
//   generatedKnownTypes — the set of resource types the runner registers.
//                         Single source of truth for "is this type known?";
//                         exposed publicly as validate.KnownTypes.
//
//   generatedSchemas    — per-type attribute name set, scraped from the
//                         executor source. Merged with typeConstraints
//                         (semantic rules — required/absPath/mode/etc.) in
//                         init() to produce TypeSchemas.
//
// Regenerate: scripts/gen-executor-schemas.sh > server/validate/schemas_gen.go

package validate

// generatedKnownTypes mirrors the runner's executors.insert(...) keys —
// every resource type a module YAML can use. The exported KnownTypes alias
// in validate.go points at this map; do not hand-maintain a parallel set.
var generatedKnownTypes = map[string]bool{
GOHEADER

# Emit generatedKnownTypes — keys mirror executors.insert(...).
for type_name in $(echo "${!TYPE_FILES[@]}" | tr ' ' '\n' | sort); do
    echo "	\"$type_name\": true,"
done

echo "}"
echo
echo "// generatedSchemas maps resource type names to attribute names extracted"
echo "// from executor source code. Merged into TypeSchemas at init time."
echo "var generatedSchemas = map[string][]string{"

for type_name in $(echo "${!TYPE_FILES[@]}" | tr ' ' '\n' | sort); do
    files="${TYPE_FILES[$type_name]}"
    # Follow shared helpers. The network_* / cisco_* / junos_* / ssh_exec
    # executors delegate SSH connection handling to network_common.rs, which
    # reads host/port/username/credential/state via params.get(...). Those
    # params are auto-injected and real, but live in the helper, not the
    # type's own file — without this the schema undercounts them and the
    # doc-parity guard would false-flag correctly-documented params.
    if grep -ql 'network_common' $files 2>/dev/null; then
        files="$files $EXEC_DIR/network_common.rs"
    fi
    # Extract params from:
    #   - direct  params.get("name")  calls (and the .get("name") shape generally)
    #   - helper-call shapes like  push_repeated(&mut args, params, "name", "-flag")
    #     or  push_single(&mut args, params, "name", "-flag")
    #   - the  require_param!(params, "name", result)  macro used by the
    #     network_common helpers (network_*, cisco_*, junos_* executors).
    # Join lines first to catch multi-line patterns.
    params=$(cat $files 2>/dev/null | tr '\n' ' ' | grep -oP '(?:params\s*\.get\(\s*"|push_(?:repeated|single)\([^,]+,\s*params,\s*"|require_param!\(\s*[^,]+,\s*")\K[^"]+' | grep -v '^_' | sort -u || true)
    if [[ -z "$params" ]]; then
        echo "	\"$type_name\": {},"
    else
        param_list=$(echo "$params" | sed 's/.*/"&"/' | paste -sd, -)
        echo "	\"$type_name\": {$param_list},"
    fi
done

echo "}"
echo
echo "// generatedStateTypes is the set of resource types whose executor actually"
echo "// consumes a \`state\` param — a direct params.get(\"state\") or the"
echo "// network_common::parse_state(params) helper. It drives the mandatory-state"
echo "// validation rule (validate.go requires \`state\` iff the type is in this set)."
echo "//"
echo "// Scanned from each type's OWN executor file(s) only — deliberately NOT the"
echo "// shared network_common.rs helper. The schema scrape above follows"
echo "// network_common (so SSH-transport params attribute correctly), which would"
echo "// otherwise mark ssh_exec / cisco_interface / junos_interface as"
echo "// state-bearing even though they never call parse_state. Keying off own-file"
echo "// consumption excludes those false positives."
echo "var generatedStateTypes = map[string]bool{"
for type_name in $(echo "${!TYPE_FILES[@]}" | tr ' ' '\n' | sort); do
    own_files="${TYPE_FILES[$type_name]}"
    # Join lines first (some executors split `params\n.get("state")` across
    # lines, e.g. package_windows.rs), then match either idiom.
    if cat $own_files 2>/dev/null | tr '\n' ' ' | grep -Pq 'params\s*\.get\(\s*"state"\)|parse_state\(\s*params\s*\)'; then
        echo "	\"$type_name\": true,"
    fi
done
echo "}"
