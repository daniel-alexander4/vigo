func runSpannerAddSpoke(cmd *cobra.Command, args []string) error {
	spokeID := args[0]
	addr, _ := cmd.Flags().GetString("addr")
	patterns, _ := cmd.Flags().GetStringSlice("patterns")
	output, _ := cmd.Flags().GetString("output")

	// Generate sample server.yaml for the spoke.
	sample := fmt.Sprintf(`# Vigo Server Configuration — Spoke: %s
# Generated by: vigocli spanner add-spoke
# Deploy this file as server.yaml on the spoke server.

server:
  grpc_listen: ":1530"
  api_listen: ":8443"
  tls:
    cert_file: "tls/cert"
    key_file: "tls/key"
    ca_file: "tls/ca"
    ca_key_file: "tls/ca_key"

database:
  dsn: "vigo.db"

spanner:
  role: spoke
  spoke_id: "%s"
  hub_addr: "%s"

checkin:
  interval: "15s"

secrets:
  backend: local
`, spokeID, spokeID, addr)

	// Determine hub address from the CLI's server config.
	client := newAPIClient()
	var status struct {
		Role string `json:"role"`
	}
	if err := client.get("/api/v1/spanner/status", &status); err != nil {
		return fmt.Errorf("cannot reach hub: %w", err)
	}
	if status.Role != "hub" {
		return fmt.Errorf("this server is %q, not a hub — run this command against the hub", status.Role)
	}

	// Print or write the sample config.
	if output != "" {
		if err := os.WriteFile(output, []byte(sample), 0644); err != nil {
			return fmt.Errorf("writing sample config: %w", err)
		}
		fmt.Printf("  Sample spoke config written to %s\n", output)
	} else {
		fmt.Println("  --- Sample spoke server.yaml ---")
		fmt.Print(sample)
		fmt.Println("  --------------------------------")
	}

	fmt.Println()
	fmt.Printf("  Add this spoke entry to your hub's server.yaml:\n\n")
	fmt.Printf("    spanner:\n")
	fmt.Printf("      spokes:\n")
	fmt.Printf("        - id: %q\n", spokeID)
	fmt.Printf("          addr: %q\n", addr)
	fmt.Printf("          patterns: [%s]\n", quotePatterns(patterns))
	fmt.Println()
	fmt.Println("  Then restart the hub to apply the change.")

	return nil
}

func runSpannerRemoveSpoke(cmd *cobra.Command, args []string) error {
	spokeID := args[0]

	if !confirmAction(fmt.Sprintf("Remove spoke %q? This will drain all envoys first.", spokeID)) {
		fmt.Println("Cancelled.")
		return nil
	}

	client := newAPIClient()

	// Drain first.
	var drainResp struct {
		Moved  int32    `json:"Moved"`
		Failed int32    `json:"Failed"`
		Errors []string `json:"Errors"`
	}
	if err := client.post("/api/v1/spanner/spokes/"+spokeID+"/drain", map[string]string{}, &drainResp); err != nil {
		return fmt.Errorf("drain failed: %w", err)
	}

	fmt.Printf("  Spoke %s drained: %d moved, %d failed.\n", spokeID, drainResp.Moved, drainResp.Failed)
	for _, e := range drainResp.Errors {
		fmt.Printf("  %s %s\n", red("Error:"), e)
	}

	fmt.Println()
	fmt.Printf("  Remove the spoke entry from your hub's server.yaml:\n\n")
	fmt.Printf("    # Remove from spanner.spokes:\n")
	fmt.Printf("    #   - id: %q\n", spokeID)
	fmt.Println()
	fmt.Println("  Then restart the hub to apply the change.")

	return nil
}

func quotePatterns(patterns []string) string {
	quoted := make([]string, len(patterns))
	for i, p := range patterns {
		quoted[i] = fmt.Sprintf("%q", p)
	}
	return strings.Join(quoted, ", ")
}

func runSpannerStatus(cmd *cobra.Command, args []string) error {
	client := newAPIClient()

	var resp struct {
		Role    string `json:"role"`
		SpokeID string `json:"spoke_id"`
		Spokes  []struct {
			ID             string   `json:"id"`
			Addr           string   `json:"addr"`
			Patterns       []string `json:"patterns"`
			Healthy        bool     `json:"healthy"`
			EnvoyCount    int32    `json:"envoy_count"`
			Converged      int32    `json:"converged"`
			Relapsed       int32    `json:"relapsed"`
			Diverged       int32    `json:"diverged"`
			Failed         int32    `json:"failed"`
			LostContact    int32    `json:"lost_contact"`
			NoData         int32    `json:"no_data"`
			ConvergencePct  float32  `json:"compliance_pct"`
			LatencyMs      int64    `json:"latency_ms"`
			Error          string   `json:"error"`
		} `json:"spokes"`
	}

	if err := client.get("/api/v1/spanner/status", &resp); err != nil {
		return fmt.Errorf("cannot reach server: %w", err)
	}

	fmt.Printf("  Role: %s\n", bold(resp.Role))

	if resp.SpokeID != "" {
		fmt.Printf("  Spoke ID: %s\n", resp.SpokeID)
	}

	if resp.Role == "standalone" {
		fmt.Println("  No spanner configured.")
		return nil
	}

	if len(resp.Spokes) == 0 {
		return nil
	}

	// Count healthy/total
	healthy := 0
	var totalEnvoys int32
	for _, s := range resp.Spokes {
		if s.Healthy {
			healthy++
		}
		totalEnvoys += s.EnvoyCount
	}

	fmt.Printf("  Spokes: %d (%d healthy)\n", len(resp.Spokes), healthy)
	fmt.Printf("  Total Envoys: %d\n\n", totalEnvoys)

	w := tabwriter.NewWriter(os.Stdout, 0, 0, 2, ' ', 0)
	fmt.Fprintf(w, "  %s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n", header("ID"), header("ADDRESS"), header("ENVOYS"), header("COMPLIANT"), header("COMPLIANCE"), header("LATENCY"), header("PATTERNS"), header("STATUS"))
	for _, s := range resp.Spokes {
		status := colorStatus("healthy")
		if !s.Healthy {
			status = colorStatus("unreachable")
		}
		patterns := strings.Join(s.Patterns, ", ")
		compliant := fmt.Sprintf("%d/%d", s.Converged, s.EnvoyCount)
		convPct := fmt.Sprintf("%.1f%%", s.ConvergencePct)
		latency := fmt.Sprintf("%dms", s.LatencyMs)
		fmt.Fprintf(w, "  %s\t%s\t%d\t%s\t%s\t%s\t%s\t%s\n", s.ID, s.Addr, s.EnvoyCount, compliant, convPct, latency, patterns, status)
	}
	w.Flush()

	return nil
}

